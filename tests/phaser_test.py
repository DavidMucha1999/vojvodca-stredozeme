import os, sys
from playwright.sync_api import sync_playwright
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
fails = []
def check(name, ok, info=''):
    print(('OK   ' if ok else 'CHYBA') + ' ' + name + (' – ' + str(info) if info != '' else ''))
    if not ok: fails.append(name)

with sync_playwright() as p:
    b = p.chromium.launch(args=['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist']); pg = b.new_page(viewport={'width': 960, 'height': 640}); pg.set_default_timeout(180000)
    errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.route('**/fonts.googleapis.com/**', lambda r: r.abort())
    pg.on('console', lambda m: m.type == 'error' and 'ERR_' not in m.text and errs.append('console: ' + m.text))
    pg.goto('file://' + os.path.join(ROOT, 'Vojvodca Stredozeme.html')); pg.wait_for_timeout(4000)
    try: pg.wait_for_function("typeof game !== 'undefined' && game.scene.getScenes(true).some(s => s.sys.settings.key === 'Intro')", timeout=30000)
    except Exception: pass
    pg.evaluate("OPT.loadScr = false")   # načítavaciu obrazovku pred bitkou skúša len 3D časť nižšie
    pg.evaluate("window.__played = 0; { const p0 = SoundFX.play; SoundFX.play = k => { const r = p0(k); if (r) __played++; return r; }; }")
    E = pg.evaluate
    def waitfor(cond, ms=3000):
        try: pg.wait_for_function(cond, timeout=ms)
        except Exception: pass
    scenes = lambda: E("game.scene.getScenes(true).map(s => s.sys.settings.key).sort((a, b) => a === 'UI' ? 1 : b === 'UI' ? -1 : 0).join(',')")
    check('Úvod a rozhranie bežia', scenes() == 'Intro,UI', scenes())
    check('Zvuky dekódované', E("Object.values(SFX).flat().length") >= 20, E("Object.values(SFX).flat().length"))
    pg.click('text=Nová hra'); pg.wait_for_timeout(300); pg.click('text=Vyraziť do boja'); pg.wait_for_timeout(400)
    waitfor("!!game.scene.getScene('UI').dlg", 15000)
    check('Návod je okno v Phaseri', E("!!game.scene.getScene('UI').dlg && ov.classList.contains('mirror')"))
    clk = lambda t: E("t => { const b = [...document.querySelectorAll('#bt button')].find(b => b.textContent.trim().startsWith(t)); if (!b) return false; b.click(); return true; }", t)
    check('Klik na Rozumiem', clk('Rozumiem')); pg.wait_for_timeout(200)
    check('Klik na Na cestu', clk('Na cestu')); pg.wait_for_timeout(400)
    check('Mapa beží', scenes() == 'Map,UI', scenes())
    for cond in ["game.scene.getScene('UI').hudLayer.list.length > 10", "game.scene.getScene('UI').barLayer.list.length >= 26"]:
        try: pg.wait_for_function(cond, timeout=3000)
        except Exception: pass
    check('Horná lišta v Phaseri', E("game.scene.getScene('UI').hudLayer.list.length") > 10, E("game.scene.getScene('UI').hudLayer.list.length"))
    check('Panel tlačidiel v Phaseri', E("game.scene.getScene('UI').barLayer.list.length") >= 26, E("game.scene.getScene('UI').barLayer.list.length"))
    E("G.camp = 1"); pg.wait_for_timeout(2500)
    check('Armády na mape', E("game.scene.getScene('Map').armies.size") == E("E.length"), E("E.length"))
    E("ov.classList.add('hide'); mode = 'map'; town(0)"); pg.wait_for_timeout(300)
    try: pg.wait_for_function("game.scene.getScene('UI').dlgButtons && game.scene.getScene('UI').dlgButtons.length === document.querySelectorAll('#bt button').length", timeout=3000)
    except Exception: pass
    check('Menu hradu v Phaseri', E("game.scene.getScene('UI').dlgButtons.length") == E("document.querySelectorAll('#bt button').length"), (E("game.scene.getScene('UI').dlgButtons.length"), E("document.querySelectorAll('#bt button').length"), E("document.querySelector('#ov h1').textContent")))
    for c in 'revhd':
        E(f"tsub(0, '{c}')"); pg.wait_for_timeout(120)
    check('Podmenu hradu bez chýb', not errs, errs[:2])
    E("tsub(0, 'e')"); pg.wait_for_timeout(200)
    waitfor("game.scene.getScene('UI').dlg && game.scene.getScene('UI').dlg.title === 'Kováč a zbrojnica'")
    check('Ikonky výbavy u kováča', E("document.querySelectorAll('#bt button canvas.ico').length") == 6 and E("game.textures.list && Object.keys(game.textures.list).filter(k => k.startsWith('ico_')).length") >= 5)
    E("for (let i = 0; i < 60; i++) LOG.unshift('Deň ' + i + ': dlhý záznam v denníku, ktorý sa určite nezmestí na jednu obrazovku, keď ich je veľa.'); ov.classList.add('hide'); mode = 'map'; dnk()")
    waitfor("game.scene.getScene('UI').dlg && game.scene.getScene('UI').dlg.title === 'Denník udalostí'")
    check('Dlhý denník: Zavrieť je vždy viditeľné', E("(() => { const d = game.scene.getScene('UI').dlg; return d.CH > d.maxH && d.root.list.some(o => o.text === 'Zavrieť'); })()"))
    E("game.scene.getScene('UI').scrollDialog(1e5, true)")
    check('Dlhý denník sa dá posunúť', E("game.scene.getScene('UI').dlg.scroll") > 0)
    clk('Zavrieť'); pg.wait_for_timeout(200)
    check('Denník sa zavrie', E("ov.classList.contains('hide')"))
    E("ov.classList.add('hide'); mode = 'map'; ency('l')"); pg.wait_for_timeout(300)
    check('Encyklopédia ostáva v HTML', E("!game.scene.getScene('UI').dlg && !ov.classList.contains('mirror')"))
    E("ov.classList.add('hide'); ov.classList.remove('encv'); mode = 'map'; LEG = true; G.eq.w = SH[0].it.length - 2"); pg.wait_for_timeout(300)
    waitfor("game.scene.getScene('UI').legLayer.list.length > 20")
    check('Legenda v Phaseri', E("game.scene.getScene('UI').legLayer.list.length") > 20)
    # 3D bitka (js/engine/3d/b3d.js): bojisko a vojaci v Three.js pod priehľadným Phaserom
    E("LEG = false; OPT.gfx = 'med'; OPT.intro3d = true; OPT.loadScr = true; startBattle(E.find(e => hos(e.f, G.fac) && !e.nz))")
    waitfor("LoadScr.on", 20000)
    check('Načítavacia obrazovka pred bitkou ', E("LoadScr.on && !!document.querySelector('#loadScr canvas')"), E("[LoadScr.on, mode, game.scene.isActive('Battle'), game.scene.getScene('Battle').ready]"))
    waitfor("!LoadScr.on && game.scene.getScene('Battle').ready", 60000)
    check('Po načítaní zmizne a boj začne', E("!LoadScr.on && game.scene.getScene('Battle').ready === true"))
    E("OPT.loadScr = false")
    check('3D bitka beží', E("B3.isOn() && document.getElementById('b3d').style.display === 'block'"), E("[typeof THREE, B3.want()]"))
    pg.wait_for_timeout(1500)
    check('3D: každý vojak má model', E("U.filter(u => !u.fled).every(u => !!B3.rigOf(u))"))
    gfx3 = E("(() => { let sk = 0, gr = 0, sky = 0; B3.scene.traverse(o => { if (o.isSkinnedMesh) sk++; if (o.geometry && o.geometry.isInstancedBufferGeometry) gr++; if (o.geometry && o.geometry.type === 'SphereGeometry' && o.material.side === THREE.BackSide) sky++; }); return [sk + U.filter(u => !u.fled && B3.rigOf(u) && B3.rigOf(u).far).length, U.filter(u => !u.fled && !u.boss && !(B3.rigOf(u) && B3.rigOf(u).tp.beast)).length, gr, sky, BI, B3.intro]; })()"); check('3D grafika: kostrové postavy (vzdialení v hromadnej sieti), tráva, obloha, nálet kamery', gfx3[0] >= gfx3[1] and (gfx3[2] == 1 or gfx3[4] == 'a') and gfx3[3] == 1 and gfx3[5], gfx3)
    E("dispatchEvent(new KeyboardEvent('keydown', { key: 'x' })); dispatchEvent(new KeyboardEvent('keyup', { key: 'x' }))"); E("for (let i = 0; i < 20; i++) B3.frame(1)")
    check('3D: kláves preskočí nálet kamery', E("!B3.intro"))
    E("dispatchEvent(new KeyboardEvent('keydown', { key: 'p' }))"); pg.wait_for_timeout(300); t0 = E("JSON.stringify(U.map(u => [u.x, u.y, u.hp]))"); pg.wait_for_timeout(1200)
    check('3D: fotorežim zastaví hru a skryje rozhranie', E("B3.photo && !game.scene.getScene('UI').sys.settings.visible") and E("JSON.stringify(U.map(u => [u.x, u.y, u.hp]))") == t0, E("[B3.photo, game.scene.getScene('UI').sys.settings.visible]"))
    E("dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape' }))"); pg.wait_for_timeout(300)
    check('3D: Esc ukončí fotorežim', E("!B3.photo && game.scene.getScene('UI').sys.settings.visible"))
    x0 = E("[U[0].x, U[0].y]"); E("keys.w = 1; for (let i = 0; i < 20; i++) updBattle(1); keys.w = 0"); x1 = E("[U[0].x, U[0].y]")
    check('3D: WASD vzhľadom na kameru (W = smer pohľadu)', ((x1[0]-x0[0]) * __import__('math').cos(E("B3.yaw")) + (x1[1]-x0[1]) * __import__('math').sin(E("B3.yaw"))) > 3, (x0, x1, E("B3.yaw")))
    check('3D: myš mieri na zem', E("(() => { const q = B3.pick(W * RES / 2, H * RES * .7); return !!q && Math.hypot(q.x - U[0].x, q.y - U[0].y) < 400; })()"))
    E("for (const u of U) if (u.t) u.hp = 0"); pg.wait_for_timeout(500)
    waitfor("mode === 'over'", 60000); clk('Prepustiť'); clk('Zajať'); clk('Pokračovať'); waitfor("game.scene.isActive('Map') && !game.scene.isActive('Battle')", 60000); pg.wait_for_timeout(600)
    check('3D sa po bitke skryje', E("!B3.isOn() && document.getElementById('b3d').style.display === 'none'"))
    E("ov.classList.add('hide'); mode = 'map'")
    E("LEG = false; OPT.gfx = 'low'; startBattle(E.find(e => hos(e.f, G.fac) && !e.nz))"); pg.wait_for_timeout(1500)
    waitfor("game.scene.isActive('Battle') && !game.scene.isActive('Map')", 8000)
    check('Bitka beží', scenes() == 'Battle,UI', scenes())
    waitfor("game.scene.getScene('Battle').ready", 60000)
    E("U[0].hp = 1e9; for (const u of U) if (u.t) u.hp = Math.min(u.hp, 2)"); pg.wait_for_timeout(5000)
    check('Zvuky zo súborov hrajú', E("__played") > 0, E("__played"))
    E("for (const u of U) if (u.t) u.hp = 0"); pg.wait_for_timeout(500)
    waitfor("mode === 'over' && !!game.scene.getScene('UI').dlg")
    check('Koniec bitky: okno v Phaseri', E("mode") == 'over' and E("!!game.scene.getScene('UI').dlg"), E("mode"))
    clk('Prepustiť'); clk('Zajať'); clk('Pokračovať'); pg.wait_for_timeout(300)
    E("ov.classList.add('hide'); mode = 'map'; G.inf = 30; const i = TW.findIndex(t => hos(t.f, G.fac) && t.f !== 9); siege(i); TW[i].sg.lad = 1; siegeMenu(i)"); pg.wait_for_timeout(200)
    clk('Zaútočiť'); pg.wait_for_timeout(800)
    check('Obliehanie', scenes() == 'Battle,UI' and E("!!SGB"), E("JSON.stringify(SGB)"))
    E("G.king = 1; KD = 0; for (const u of U) if (u.t) u.hp = 0"); pg.wait_for_timeout(600)
    clk('Pokračovať'); pg.wait_for_timeout(400)
    check('Korunovácia ostáva v HTML (formulár)', E("ov.classList.contains('mirror')") == False and E("!!document.querySelector('#bt input')"))
    E("[...document.querySelectorAll('#bt button')].find(b => b.textContent === 'Strana zla').click()"); pg.wait_for_timeout(100)
    clk('Potvrdiť korunováciu'); pg.wait_for_timeout(200)
    check('Korunovácia: výber strany zla', E("G.side === 1 && shopSide(6) === 1"), E("G.side"))
    check('Žiadne chyby na stránke', not errs, errs[:3])
    b.close()
print('\nVšetky testy prešli.' if not fails else '\nZlyhalo: ' + ', '.join(fails))
sys.exit(1 if fails else 0)
